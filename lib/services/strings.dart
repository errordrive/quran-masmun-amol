// UI strings — Bangla by default, English as the toggle option.
// `tr(key)` reads the current UI language from AppState and falls back
// to English, then to the key itself, so a missing key never crashes.
import 'app_state.dart';

String tr(String key) {
  final lang = AppState.instance.uiLang;
  return _strings[lang]?[key] ?? _strings['en']?[key] ?? key;
}

/// Prayer name shown in the UI (Bangla names in Bangla mode).
String prayerName(String english) {
  if (!AppState.instance.isBangla) return english;
  switch (english) {
    case 'Fajr':
      return 'ফজর';
    case 'Dhuhr':
      return 'যোহর';
    case 'Asr':
      return 'আসর';
    case 'Maghrib':
      return 'মাগরিব';
    case 'Isha':
      return 'এশা';
    case 'Sunrise':
      return 'সূর্যোদয়';
    default:
      return english;
  }
}

